// Generator for lib/website-whatsapp-messages.ts
// Run from the project root:   node scripts/extract-wa-messages.mjs
// Re-run it whenever a website WhatsApp message is added or changed, then review the diff.

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { extract } from "./wa-message-extract.mjs"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const result = extract(root)

// Fail closed: never write a list while something is unclassified.
if (result.unreviewed.length || result.approvedMissing.length) {
  if (result.unreviewed.length) {
    console.error("UNREVIEWED website messages (in neither list of scripts/wa-message-review.mjs):")
    result.unreviewed.forEach((m) => console.error(`  ? ${m.raw}   [${[...m.files].join(", ")}]`))
    console.error("Classify each one by hand as APPROVED_SPECIFIC or GENERIC_EXCLUDED. Nothing was written.")
  }
  if (result.approvedMissing.length) {
    console.error("APPROVED messages that no longer exist on the website (remove them from the review file):")
    result.approvedMissing.forEach((k) => console.error(`  - ${k}`))
    console.error("Nothing was written.")
  }
  process.exit(1)
}

const body = result.approved.map((m) => `  ${JSON.stringify(m.raw)},`).join("\n")

const out = `// AUTO-GENERATED by scripts/extract-wa-messages.mjs. Do not edit by hand.
//
// Exact pre-filled WhatsApp messages used by the website buttons that are specific to one
// service or project. The webhook uses this list to set CHANNEL = "Website WhatsApp" only
// when an incoming message matches one of them exactly (after normalizing case, spaces and
// trailing punctuation).
//
// Left out on purpose: the generic messages, dynamic templates, form-generated messages and
// links without a message. They never set CHANNEL.

export const WEBSITE_WHATSAPP_MESSAGES: readonly string[] = [
${body}
]
`

fs.writeFileSync(path.join(root, "lib", "website-whatsapp-messages.ts"), out)

console.log(`Messages found on the website (distinct): ${result.totalDistinct}`)
console.log(`Excluded generic messages (reviewed):    ${result.excluded.length}`)
console.log(`Unreviewed messages:                     ${result.unreviewed.length}`)
console.log(`Approved exact messages written:         ${result.approved.length}`)
console.log(`Not used - dynamic template links:       ${result.templates}`)
console.log(`Not used - bare links (no message):      ${result.bare}`)
if (result.genericMissing.length) {
  console.warn("WARNING: excluded generic messages no longer found on the website:")
  result.genericMissing.forEach((g) => console.warn("  - " + g))
}
